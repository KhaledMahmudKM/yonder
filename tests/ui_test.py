import time, sys
from playwright.sync_api import sync_playwright
U = "http://127.0.0.1:8022/"
import os
S = os.path.join(os.path.dirname(os.path.abspath(__file__)), "shots") + "/"
os.makedirs(S, exist_ok=True)
errors = []
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=os.environ.get("CHROME") or None, args=["--no-sandbox"])  # CHROME=/path/to/chrome to use your own
    ctx = b.new_context(viewport={"width": 1440, "height": 860})
    ctx.grant_permissions(["clipboard-read", "clipboard-write"], origin=U.rstrip("/"))
    pg = ctx.new_page()
    pg.on("pageerror", lambda e: errors.append(f"pageerror: {e}"))
    pg.on("console", lambda m: m.type == "error" and errors.append(f"console: {m.text}"))
    pg.goto(U); pg.wait_for_timeout(800)
    pg.screenshot(path=S + "01-launcher-empty.png")
    # save a session via the editor
    pg.get_by_role("button", name="New session…").first.click()
    d = pg.locator(".session-dlg")
    d.get_by_label("Address", exact=True).fill("127.0.0.1"); d.get_by_label("Port", exact=True).fill("2222")
    d.get_by_label("User", exact=True).fill("alice"); d.get_by_label("Name", exact=True).fill("Web server")
    d.get_by_label("Folder", exact=True).fill("Course/Lab 3"); d.get_by_label("Files start in").fill("/home/alice/projects")
    pg.screenshot(path=S + "02-session-editor.png")
    pg.get_by_role("button", name="Save and connect").click()
    pg.wait_for_selector(".connect-dlg dl.fp"); pg.wait_for_timeout(300)
    pg.screenshot(path=S + "03-hostkey.png")
    pg.get_by_role("button", name="Trust and connect").click()
    pg.wait_for_selector(".connect-dlg input[type=password]")
    pg.fill(".connect-dlg input[type=password]", "alicepw")
    pg.screenshot(path=S + "04-password.png")
    pg.get_by_role("button", name="Log in").click()
    pg.wait_for_selector(".termview:not(.is-hidden) .xterm-rows"); pg.wait_for_timeout(1500)
    pg.keyboard.type("echo hello from $(hostname); ls --color=always /etc | head -20\n")
    pg.wait_for_timeout(900)
    pg.screenshot(path=S + "05-terminal.png")
    txt = pg.inner_text(".termview:not(.is-hidden) .xterm-rows")
    if "hello from" not in txt: errors.append("terminal didn't run the command")
    # second server by quick connect (keyboard-interactive)
    pg.keyboard.press("Alt+Shift+T"); pg.wait_for_timeout(300)
    pg.get_by_label("Quick connect: user@address[:port]").fill("bob@127.0.0.1:2223")
    pg.get_by_role("button", name="Terminal", exact=True).first.click()
    pg.get_by_role("button", name="Trust and connect").click()
    pg.fill(".connect-dlg input[type=password]", "bobpw"); pg.get_by_role("button", name="Log in").click()
    pg.wait_for_timeout(1500)
    pg.keyboard.type("top -b -n1 | head -12\n"); pg.wait_for_timeout(800)
    tabs = pg.locator(".tab").count()
    if tabs != 2: errors.append(f"expected 2 tabs, got {tabs}")
    # files tab for alice via the session's Files
    pg.locator(".tab").nth(0).click(button="right"); pg.wait_for_timeout(200)
    pg.screenshot(path=S + "06-tab-menu.png")
    pg.get_by_role("menuitem", name="Files on this server").click()
    pg.wait_for_selector(".files:not(.is-hidden) .files-pane"); pg.wait_for_timeout(1200)
    # left pane: switch to bob's server
    left = pg.locator(".files:not(.is-hidden) .files-pane").nth(0)
    right = pg.locator(".files:not(.is-hidden) .files-pane").nth(1)
    left.locator("select").select_option("s:bob@127.0.0.1:2223"); pg.wait_for_timeout(800)
    # drag "site" from right (alice) to left (bob)
    right.locator("tr[data-name='site']").drag_to(left.locator(".files-list"))
    pg.wait_for_timeout(1500)
    pg.screenshot(path=S + "07-files-copied.png")
    import os
    if not os.path.exists("/home/bob/site/nginx.conf"): errors.append("drag copy alice->bob didn't happen")
    elif oct(os.stat("/home/bob/site").st_mode & 0o777) != "0o755": errors.append(f"folder rights not kept: {oct(os.stat('/home/bob/site').st_mode & 0o777)}")
    # edit a file
    right.locator("tr[data-name='site']").dblclick(); pg.wait_for_timeout(600)
    right.locator("tr[data-name='nginx.conf']").dblclick(); pg.wait_for_selector(".editor textarea"); pg.wait_for_timeout(300)
    pg.locator(".editor textarea").press("Control+End"); pg.keyboard.type("# edited in Yonder\n")
    pg.screenshot(path=S + "08-editor.png")
    pg.keyboard.press("Control+s"); pg.wait_for_timeout(700)
    pg.get_by_role("button", name="Close", exact=True).click()
    if "edited in Yonder" not in open("/home/alice/projects/site/nginx.conf").read(): errors.append("editor didn't save")
    # context menu on a file row + permissions
    right.locator("tr[data-name='nginx.conf']").click(button="right"); pg.wait_for_timeout(200)
    pg.screenshot(path=S + "09-file-menu.png")
    pg.get_by_role("menuitem", name="Permissions…").click(); pg.wait_for_timeout(200)
    pg.locator(".chmod input[type=checkbox]").nth(4).check()  # group write
    pg.screenshot(path=S + "10-chmod.png")
    pg.get_by_role("button", name="Set", exact=True).click(); pg.wait_for_timeout(600)
    m = os.stat("/home/alice/projects/site/nginx.conf").st_mode & 0o777
    if m != 0o664: errors.append(f"chmod -> {oct(m)}")
    # terminal here
    right.get_by_role("button", name="Terminal here").click(); pg.wait_for_timeout(1500)
    pg.keyboard.type("pwd\n"); pg.wait_for_timeout(500)
    txt = pg.inner_text(".termview:not(.is-hidden) .xterm-rows")
    if "/home/alice/projects/site" not in txt: errors.append("terminal here: wrong folder: " + txt[-200:])
    pg.screenshot(path=S + "11-terminal-here.png")
    # reload: terminals come back with their screens
    n_before = pg.locator(".tab").count()
    pg.on("dialog", lambda d: d.accept())
    pg.reload(); pg.wait_for_timeout(2500)
    if pg.locator(".tab").count() != n_before: errors.append("tabs lost on reload")
    pg.locator(".tab").nth(0).click(); pg.wait_for_timeout(800)
    txt = pg.inner_text(".termview:not(.is-hidden) .xterm-rows")
    if "hello from" not in txt: errors.append("reattach after reload lost the screen")
    pg.screenshot(path=S + "12-after-reload.png")
    # settings
    pg.get_by_role("button", name="Menu").click(); pg.get_by_role("menuitem", name="Themes…").click(); pg.wait_for_timeout(200)
    pg.get_by_role("radio", name="Paper (light)").click(); pg.wait_for_timeout(300)
    pg.screenshot(path=S + "13-settings.png")
    pg.get_by_role("button", name="Use Paper (light)").click(); pg.wait_for_timeout(400)
    pg.screenshot(path=S + "14-light-theme.png")
    pg.get_by_role("button", name="Menu").click(); pg.get_by_role("menuitem", name="Themes…").click()
    pg.get_by_role("radio", name="Slate (dark)").click(); pg.get_by_role("button", name="Use Slate (dark)").click(); pg.wait_for_timeout(300)
    # exit the shell -> ended, Enter -> new
    pg.keyboard.type("exit\n"); pg.wait_for_timeout(800)
    txt = pg.inner_text(".termview:not(.is-hidden) .xterm-rows")
    if "session ended" not in txt: errors.append("exit not shown")
    pg.keyboard.press("Enter"); pg.wait_for_timeout(1500)
    st = pg.locator(".tab.is-active .dot").get_attribute("class")
    if "is-ok" not in st: errors.append("Enter didn't start a new session: " + st)
    # new tab launcher with saved sessions + sidebar
    pg.keyboard.press("Alt+Shift+T"); pg.wait_for_timeout(400)
    pg.screenshot(path=S + "15-launcher.png")
    b.close()
print("ERRORS:", errors)
